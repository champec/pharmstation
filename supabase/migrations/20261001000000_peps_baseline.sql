CREATE OR REPLACE FUNCTION public.ps_peps_prescribers_guard()
 RETURNS trigger
 LANGUAGE plpgsql
 SET search_path TO 'public'
AS $function$
begin
  -- Trusted callers: service role, and the admin RPC below (runs as the function owner).
  if coalesce(auth.role(), '') = 'service_role' or current_user in ('postgres', 'supabase_admin') then
    return new;
  end if;

  if tg_op = 'INSERT' then
    new.status := 'pending';
    new.approved_by := null;
    new.approved_at := null;
    return new;
  end if;

  new.status := old.status;
  new.approved_by := old.approved_by;
  new.approved_at := old.approved_at;
  if new.full_name is distinct from old.full_name
     or new.prescriber_type is distinct from old.prescriber_type
     or new.registration_number is distinct from old.registration_number
     or new.registration_body is distinct from old.registration_body
     or new.user_id is distinct from old.user_id then
    new.status := 'pending';
    new.approved_by := null;
    new.approved_at := null;
  end if;
  return new;
end;
$function$
;

revoke execute on function public.ps_peps_prescribers_guard() from public, anon, authenticated;

CREATE OR REPLACE FUNCTION public.ps_peps_prescription_guard()
 RETURNS trigger
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO 'public'
AS $function$
