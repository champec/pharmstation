begin
  if NEW.assigned_org_id is null then
    return NEW;
  end if;
  if TG_OP = 'UPDATE' and OLD.assigned_org_id is not distinct from NEW.assigned_org_id then
    return NEW;
  end if;

  v_patient := coalesce(nullif(NEW.patient_snapshot->>'full_name', ''), 'A patient');

  perform ps_fanout_notification(
    NEW.assigned_org_id,
    'peps',
    'New private prescription received',
    v_patient || ' — Rx ' || NEW.prescription_ref,
    '/peps/' || NEW.id::text,
    jsonb_build_object('prescription_id', NEW.id)
  );
  return NEW;
end;
$function$
;

