CREATE OR REPLACE FUNCTION public.ps_peps_set_signing_pin(p_new_pin text, p_current_pin text DEFAULT NULL::text)
 RETURNS void
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO 'public'
AS $function$
declare k ps_peps_signing_keys;
begin
  if auth.uid() is null then raise exception 'Not signed in'; end if;
  if not exists (select 1 from ps_peps_prescribers where user_id = auth.uid()) then
    raise exception 'Register as a prescriber first';
  end if;
  if coalesce(p_new_pin, '') !~ '^\d{6}$' then raise exception 'Your signing PIN must be 6 digits'; end if;
  if p_new_pin ~ '^(\d)\1{5}$' or p_new_pin in ('123456', '654321', '012345', '123123') then
    raise exception 'Choose a less obvious PIN';
  end if;
  select * into k from ps_peps_signing_keys where user_id = auth.uid() for update;
  if found then
    if k.locked_until is not null and k.locked_until > now() then
      raise exception 'Too many wrong PINs. Try again after %', to_char(k.locked_until, 'HH24:MI');
    end if;
    if p_current_pin is null or extensions.crypt(p_current_pin, k.pin_hash) <> k.pin_hash then
      raise exception 'Your current PIN is not right';
    end if;
    update ps_peps_signing_keys
       set pin_hash = extensions.crypt(p_new_pin, extensions.gen_salt('bf', 10)), failed_count = 0,
           locked_until = null, updated_at = now()
     where user_id = auth.uid();
  else
    insert into ps_peps_signing_keys (user_id, pin_hash)
    values (auth.uid(), extensions.crypt(p_new_pin, extensions.gen_salt('bf', 10)));
  end if;
end;
$function$
;

revoke execute on function public.ps_peps_set_signing_pin(p_new_pin text, p_current_pin text) from public, anon;
grant execute on function public.ps_peps_set_signing_pin(p_new_pin text, p_current_pin text) to authenticated;

CREATE OR REPLACE FUNCTION public.ps_peps_spine_search(p_query text)
 RETURNS TABLE(id uuid, prescription_ref text, patient_name text, prescription_date date, status text, location text, is_open boolean)
 LANGUAGE sql
 STABLE SECURITY DEFINER
 SET search_path TO 'public'
AS $function$
  select rx.id, rx.prescription_ref,
    -- Patient name only when the caller's pharmacy holds it or wrote it.
    case when rx.assigned_org_id in (select ps_peps_user_org_ids()) or rx.written_by = auth.uid()
         then coalesce(rx.patient_snapshot->>'full_name', trim(concat(rx.patient_snapshot->>'first_name', ' ', rx.patient_snapshot->>'last_name')))
         else null end as patient_name,
    rx.prescription_date, rx.status,
    case when rx.status = 'available' and rx.assigned_org_id is null then 'Spine (unclaimed)'
         when rx.status = 'dispensed' then 'Dispensed'
         when rx.status = 'cancelled' then 'Cancelled'
         else coalesce(org.name, 'A pharmacy') end as location,
    (rx.status = 'available' and rx.assigned_org_id is null) as is_open
  from ps_peps_prescriptions rx
  left join ps_organisations org on org.id = rx.assigned_org_id
  where exists (select 1 from ps_peps_user_org_ids())
    and p_query is not null
    and upper(rx.prescription_ref) = upper(trim(p_query))
  limit 1;
$function$
;

