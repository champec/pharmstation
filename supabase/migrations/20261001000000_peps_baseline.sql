CREATE OR REPLACE FUNCTION public.ps_peps_transfer(p_id uuid, p_to_org_id uuid)
 RETURNS ps_peps_prescriptions
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO 'public'
AS $function$
declare rx ps_peps_prescriptions;
begin
  select * into rx from ps_peps_prescriptions where id = p_id for update;
  if not found then raise exception 'Prescription not found'; end if;
  if rx.status <> 'held' then raise exception 'Only held prescriptions can be transferred'; end if;
  perform ps_peps_assert_member(rx.assigned_org_id);
  perform ps_peps_assert_not_expired(rx);
  if p_to_org_id is null or not ps_org_is_verified(p_to_org_id) then
    raise exception 'Prescriptions can only be transferred to a verified pharmacy';
  end if;
  if p_to_org_id = rx.assigned_org_id then raise exception 'Already held by this pharmacy'; end if;
  update ps_peps_prescriptions set status = 'available', assigned_org_id = p_to_org_id, downloaded_at = null where id = p_id;
  insert into ps_peps_events (prescription_id, event_type, from_org_id, to_org_id, actor_user_id)
  values (p_id, 'transferred', rx.assigned_org_id, p_to_org_id, auth.uid());
  select * into rx from ps_peps_prescriptions where id = p_id;
  return rx;
end;
$function$
;

revoke execute on function public.ps_peps_transfer(p_id uuid, p_to_org_id uuid) from public, anon;
grant execute on function public.ps_peps_transfer(p_id uuid, p_to_org_id uuid) to authenticated;

CREATE OR REPLACE FUNCTION public.ps_peps_verify(p_id uuid)
 RETURNS jsonb
 LANGUAGE plpgsql
 STABLE SECURITY DEFINER
 SET search_path TO 'public'
AS $function$
declare rx ps_peps_prescriptions;
begin
  select * into rx from ps_peps_prescriptions where id = p_id;
  if not found then raise exception 'Prescription not found'; end if;
  if rx.written_by is distinct from auth.uid()
     and not (rx.assigned_org_id in (select ps_peps_user_org_ids()))
     and not ps_is_platform_admin() then
    raise exception 'Prescription not found';
  end if;
  if rx.content_hash is null then
    return jsonb_build_object('status', 'unsigned');
  end if;
  return jsonb_build_object(
    'status', case when ps_peps_content_hash(p_id) = rx.content_hash then 'verified' else 'altered' end,
    'signed_at', rx.signed_at,
    'prescriber_status', (select status from ps_peps_prescribers where id = rx.prescriber_id));
end;
$function$
;

revoke execute on function public.ps_peps_verify(p_id uuid) from public, anon;
grant execute on function public.ps_peps_verify(p_id uuid) to authenticated;

